export type CcrPriority = "High" | "Medium" | "Low"

export type CcrRow = {
  reference: string
  status: string
  vendorCode: string
  vendorName: string
  signoffLevel: string
  dateRequested: string
  lastUpdated: string
  recentUpdate: string
  netPriceChange: boolean
  leadTimeChange: boolean
  moqChange: boolean
  atb: boolean
  bb: boolean
  missingRefData: boolean
  supplyOk: boolean
  priority: CcrPriority
  ccrType: string
  partRefs: string[]
}

export function fmtCcrDate(iso: string): string {
  const [y, m, d] = iso.split("-")
  return `${d}/${m}/${y}`
}

